'use strict';
/*
 * OpenAI Codex CLI adapter. Pure: inputs in, { path, content } out, no fs.
 *
 * Checked against the official docs on 2026-11-14 (developers.openai.com/codex/* now redirects to
 * learn.chatgpt.com/docs/*):
 *   Custom agents   https://developers.openai.com/codex/subagents
 *                   (→ https://learn.chatgpt.com/docs/agent-configuration/subagents)
 *     One TOML file per agent in `.codex/agents/` (project) or `~/.codex/agents/` (personal); the `name` field, not
 *     the file name, identifies it. Required: `name`, `description`, `developer_instructions` (all strings).
 *     Optional: `model`, `model_reasoning_effort` (values the page names: low, medium, high, xhigh, max, ultra),
 *     `model_reasoning_summary`, `model_verbosity`, `features.*` switches, `skills.*`.
 *     NOT per agent: `sandbox_mode`, `approval_policy`, `model_provider`, `mcp_servers` "don't override the parent
 *     configuration"; a subagent inherits the parent turn's sandbox and approvals, and the page says agent
 *     instructions "don't create a separate read-only sandbox". So the brief's capability → sandbox mapping has no
 *     documented form. This adapter writes no `sandbox_mode` (it would be silently ignored and read as a guarantee);
 *     the seat's limits go at the top of `developer_instructions`, and `access` is exported for the orchestrator's
 *     post-phase check.
 *   Skills          https://developers.openai.com/codex/skills (→ https://learn.chatgpt.com/docs/build-skills)
 *     `.agents/skills/<name>/SKILL.md`, scanned from the working directory up to the repo root; frontmatter `name`
 *     and `description` are required.
 *   Hooks           https://developers.openai.com/codex/hooks (→ https://learn.chatgpt.com/docs/hooks)
 *     `<repo>/.codex/hooks.json`: `{ "description"?, "hooks": { "<Event>": [ { "matcher", "hooks": [ { "type":
 *     "command", "command", "timeout"? } ] } ] } }`. Shell calls match as `Bash`, edits as `apply_patch` (aliases
 *     `Edit`, `Write`); both carry their text in `tool_input.command`. Exit 2 with the reason on stderr blocks a
 *     PreToolUse call. Commands run in the session cwd, which may be a subdirectory: the docs resolve repo paths
 *     with `git rev-parse --show-toplevel`. Project hooks run only once the `.codex/` layer is trusted and each hook
 *     is reviewed (`/hooks`, tied to its hash): that review is the arming act, so writing the file arms nothing.
 *   AGENTS.md       https://developers.openai.com/codex/guides/agents-md
 *                   (→ https://learn.chatgpt.com/docs/agent-configuration/agents-md)
 *     Read at the project root and in each directory down to the working directory, before any work.
 */

const { parsePersona, limitsText, agentSkill, bodyText } = require('./neutral.cjs');

const CODEX_EFFORTS = new Set(['low', 'medium', 'high', 'xhigh', 'max', 'ultra']);

/** A TOML basic string: quotes, backslashes and every control character escaped, so one value is one line. */
function tomlString(value) {
  let out = '"';
  for (const ch of String(value)) {
    const c = ch.codePointAt(0);
    if (ch === '"') out += '\\"';
    else if (ch === '\\') out += '\\\\';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\t') out += '\\t';
    else if (ch === '\r') out += '\\r';
    else if (c < 0x20 || c === 0x7f) out += `\\u${c.toString(16).padStart(4, '0').toUpperCase()}`;
    else out += ch;
  }
  return `${out}"`;
}

/**
 * renderAgent(neutralMd, { models?, file? }) → { path, content, access }.
 * `models` maps tiers to Codex model ids; a tier with no entry writes no `model` line, so the agent inherits the
 * session's model (the kit ships no Codex model defaults). `access` is the seat's neutral access level.
 */
function renderAgent(neutralMd, { models = {}, file } = {}) {
  const p = parsePersona(neutralMd);
  if (!p || !p.name) throw new Error(`codex: ${file || 'persona'} has no frontmatter name`);
  const instructions = `${limitsText(p, 'Codex')}\n\n${bodyText(p.body)}`;
  const lines = [
    `# Generated by the builder kit from agents/${file || `${p.name}.md`}. Edit the neutral persona, not this file.`,
    `# Seat access: ${p.access}. Codex applies the parent session's sandbox to every agent, so the limit is held by the`,
    '# instructions below and checked after the phase.',
    `name = ${tomlString(p.name)}`,
    `description = ${tomlString(p.description)}`,
  ];
  const model = Object.prototype.hasOwnProperty.call(models, p.tier) ? models[p.tier] : '';
  if (model) lines.push(`model = ${tomlString(model)}`);
  if (CODEX_EFFORTS.has(p.effort)) lines.push(`model_reasoning_effort = ${tomlString(p.effort)}`);
  lines.push(`developer_instructions = ${tomlString(instructions)}`);
  return { path: `.codex/agents/${p.name}.toml`, content: `${lines.join('\n')}\n`, access: p.access };
}

/** Where a kit skill lands. The same path as Antigravity's: the caller writes it once (index.cjs skillFiles()). */
const skillPath = (name) => `.agents/skills/${name}/SKILL.md`;

const renderSkill = (name, content) => ({ path: skillPath(name), content: agentSkill(name, content) });

/**
 * hooksConfig({ hooksDir? }) → { path: '.codex/hooks.json', content }.
 * Only the guard whose input Codex documents in the shape the kit's hook reads: protected-paths on `Bash`
 * (`tool_input.command`, exit 2 blocks). See `unconfirmed` for what is left out.
 */
function hooksConfig({ hooksDir = '.codex/hooks' } = {}) {
  const config = {
    description: 'Builder kit guards. Review with /hooks before trusting; untrusted hooks do not run.',
    hooks: {
      PreToolUse: [
        {
          matcher: 'Bash|mcp__.*',
          hooks: [{ type: 'command', command: `node "$(git rev-parse --show-toplevel)/${hooksDir}/protected-paths.cjs"`, timeout: 30 }],
        },
      ],
    },
  };
  return { path: '.codex/hooks.json', content: `${JSON.stringify(config, null, 2)}\n` };
}

/** Left out on purpose, each for a stated reason. */
const unconfirmed = [
  'sandbox_mode / approval_policy per agent: documented as NOT overridable in a custom agent file; seat limits are instruction-held',
  'protected-paths on apply_patch: Codex sends the patch text in tool_input.command, and the hook judges file tools by tool_input.file_path, so edits are not judged; only Bash is registered',
  'reviewer-write-guard / registry-read-guard: need the dispatching seat in the tool-hook input (agent_type); the PreToolUse/PostToolUse field tables document no agent field',
  'bash-output-cap: PostToolUse can only replace a result with feedback (updatedMCPToolOutput is "not supported yet"), not with a digest',
  'model ids: optional per agent; the kit ships no Codex defaults, so a tier with no --models entry inherits the session model',
];

module.exports = {
  id: 'codex',
  pointer: 'AGENTS.md',
  agentsDir: '.codex/agents',
  hooksDir: '.codex/hooks',
  tomlString,
  renderAgent,
  skillPath,
  renderSkill,
  hooksConfig,
  unconfirmed,
};
