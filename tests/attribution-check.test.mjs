/**
 * attribution-check (specs/repo-hygiene.spec.md, M21, REQ-1841; D99, D102, D104): trailers, footers, author identities
 * and branch names that carry an assistant or tool name, reported and never amended. Each test names its AC.
 */
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { after, describe, test } from 'node:test';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const lib = require('../scripts/lib/attribution-check.cjs');
const CLI = join(here, '..', 'scripts', 'attribution-check.mjs');

const temps = [];
after(() => { for (const d of temps) rmSync(d, { recursive: true, force: true }); });

const git = (cwd, args, env = {}) => {
  const r = spawnSync('git', args, { cwd, encoding: 'utf8', env: { ...process.env, ...env } });
  if (r.status !== 0) throw new Error(`git ${args.join(' ')}: ${r.stderr}`);
  return r.stdout.trim();
};
const profile = (repo, features) => writeFileSync(join(repo, 'PIPELINE_PROFILE.md'), `\`\`\`json pipeline-settings\n${JSON.stringify({ schema: 2, features })}\n\`\`\`\n`);
const run = (cwd, args) => {
  const r = spawnSync(process.execPath, [CLI, ...args], { cwd, encoding: 'utf8' });
  return { status: r.status, out: `${r.stdout}${r.stderr}`, stdout: r.stdout };
};

/** Three commits on main: plain, a co-author trailer naming an assistant, an assistant author with a generated footer. */
function rig() {
  const parent = realpathSync.native(mkdtempSync(join(tmpdir(), 'attribution-check-')));
  temps.push(parent);
  const repo = join(parent, 'app');
  mkdirSync(repo);
  git(repo, ['init', '-q', '-b', 'main']);
  git(repo, ['config', 'user.email', 't@example.com']);
  git(repo, ['config', 'user.name', 'T']);
  writeFileSync(join(repo, 'a.txt'), 'a\n');
  git(repo, ['add', 'a.txt']);
  git(repo, ['commit', '-q', '-m', 'init']);
  const root = git(repo, ['rev-parse', 'HEAD']);
  writeFileSync(join(repo, 'b.txt'), 'b\n');
  git(repo, ['add', 'b.txt']);
  git(repo, ['commit', '-q', '-m', 'add b', '-m', 'Co-Authored-By: Claude <noreply@anthropic.com>']);
  const trailer = git(repo, ['rev-parse', 'HEAD']);
  writeFileSync(join(repo, 'c.txt'), 'c\n');
  git(repo, ['add', 'c.txt']);
  git(repo, ['commit', '-q', '-m', 'add c', '-m', 'Generated with Claude Code'], { GIT_AUTHOR_NAME: 'Claude', GIT_AUTHOR_EMAIL: 'noreply@anthropic.com' });
  const authored = git(repo, ['rev-parse', 'HEAD']);
  return { repo, root, trailer, authored };
}

describe('attribution-check — pure', () => {
  test('red: AC-1841 the trailer shapes: co-author naming an assistant, a session line, generated footers, a robot footer; a human co-author is none', () => {
    assert.deepEqual(lib.trailerKinds('Subject\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n'), ['co-author trailer']);
    assert.deepEqual(lib.trailerKinds('Subject\n\nCo-Authored-By: Dana <dana@example.com>\n'), []);
    assert.deepEqual(lib.trailerKinds('Subject\n\nClaude-Session: https://example.com/s/1\n'), ['session line']);
    assert.deepEqual(lib.trailerKinds('Subject\n\n🤖 Generated with [Claude Code](https://example.com)\n'), ['generated footer', 'robot footer']);
    assert.deepEqual(lib.trailerKinds('Subject\n\nGenerated by Codex\n'), ['generated footer']);
    assert.deepEqual(lib.trailerKinds('Subject\n\nSigned-off-by: X <x@example.com>\n'), []);
    assert.deepEqual(lib.trailerKinds('Subject\n\nmade-by: robot9\n', ['^made-by:']), ['pattern']);
  });
  test('red: AC-1841 identities: a tool name, an assistant domain or a listed string; a person is none', () => {
    assert.equal(lib.isAssistantIdentity('Claude <noreply@anthropic.com>'), true);
    assert.equal(lib.isAssistantIdentity('Dana <dana@example.com>'), false);
    assert.equal(lib.isAssistantIdentity('bot <bot@example.com>', ['bot@example.com']), true);
    assert.equal(lib.isAssistantIdentity('Codex <x@example.com>'), true);
  });
  test('red: AC-1841c branch names: the built-in list in any segment, a pattern, and the feature/ rename', () => {
    assert.equal(lib.branchCarriesTool('claude/task-1'), true);
    assert.equal(lib.branchCarriesTool('fix/copilot-suggestion'), true);
    assert.equal(lib.branchCarriesTool('feature/y'), false);
    assert.equal(lib.branchCarriesTool('bot/x', ['^bot/']), true);
    assert.equal(lib.featureName('claude/task-1'), 'feature/task-1');
    assert.equal(lib.featureName('claude/project-thread-abc'), 'feature/project-thread-abc');
    assert.equal(lib.featureName('codex'), 'feature/topic');
  });
});

describe('attribution-check — CLI', () => {
  test('red: AC-1841 one TRAILER, one AUTHOR and one TRAILER with short SHAs and kinds, no message text, exit 1; allow by SHA → exit 0; off → not configured, exit 3', () => {
    const { repo, root, trailer, authored } = rig();
    profile(repo, { attributionCheck: { state: 'on' } });
    const r = run(repo, ['--since', root]);
    assert.equal(r.status, 1, r.out);
    const lines = r.stdout.split(/\r?\n/).filter((l) => /^(TRAILER|AUTHOR|BRANCH)/.test(l));
    assert.equal(lines.length, 3, r.stdout);
    assert.match(r.stdout, new RegExp(`^TRAILER +${trailer.slice(0, 7)} — co-author trailer`, 'm'));
    assert.match(r.stdout, new RegExp(`^TRAILER +${authored.slice(0, 7)} — generated footer`, 'm'));
    assert.match(r.stdout, new RegExp(`^AUTHOR +${authored.slice(0, 7)} — author identity`, 'm'));
    assert.doesNotMatch(r.stdout, /add b|add c|noreply@/, 'no message text, no address');
    assert.match(r.stdout, /nothing was amended, renamed or pushed/);
    profile(repo, { attributionCheck: { state: 'on', allow: [trailer.slice(0, 10), authored.slice(0, 10)] } });
    const ok = run(repo, ['--since', root]);
    assert.equal(ok.status, 0, ok.out);
    assert.match(ok.stdout, /0 finding\(s\)/);
    profile(repo, { attributionCheck: { state: 'off' } });
    const off = run(repo, ['--since', root]);
    assert.equal(off.status, 3, off.out);
    assert.equal(off.stdout.trim(), 'attributionCheck: not configured');
    const defaults = run(repo, ['--since', root, '--defaults']);
    assert.equal(defaults.status, 1, defaults.out);
    assert.match(defaults.stdout.split('\n')[0], /^attributionCheck: not configured — checking .* with the built-in lists/);
  });
  test('red: AC-1841 (D102) the amend command only for a commit not contained in the target; a contained one says a person decides; --json carries the findings', () => {
    const { repo, root, trailer } = rig();
    git(repo, ['branch', 'release']);
    writeFileSync(join(repo, 'd.txt'), 'd\n');
    git(repo, ['add', 'd.txt']);
    git(repo, ['commit', '-q', '-m', 'add d', '-m', 'Co-Authored-By: Codex <noreply@openai.com>']);
    profile(repo, { attributionCheck: { state: 'on', target: 'release' } });
    const r = run(repo, ['--since', root, '--json']);
    assert.equal(r.status, 1, r.out);
    const j = JSON.parse(r.stdout);
    assert.equal(j.check, 'attributionCheck');
    const contained = j.findings.find((f) => f.ref === trailer);
    assert.match(contained.command, /contained in release: a history rewrite is a decision for a person/);
    const head = j.findings.find((f) => f.short === git(repo, ['rev-parse', '--short=7', 'HEAD']));
    assert.match(head.command, /^git commit --amend/);
    assert.ok(j.findings.every((f) => !('body' in f) && !/noreply@/.test(JSON.stringify(f))), 'no message text, no address in the JSON');
  });
  test('red: AC-1841c BRANCH for the current claude/ branch with the rename command; none for a merged codex/ branch or feature/y; allow claude/* → none', () => {
    const { repo, root } = rig();
    git(repo, ['branch', 'codex/x', root]);
    git(repo, ['checkout', '-q', '-b', 'claude/task-1']);
    git(repo, ['branch', 'feature/y']);
    writeFileSync(join(repo, 'e.txt'), 'e\n');
    git(repo, ['add', 'e.txt']);
    git(repo, ['commit', '-q', '-m', 'plain']);
    profile(repo, { attributionCheck: { state: 'on', target: 'main', allow: ['*'] } }); // '*' allows no SHA: it is a branch glob — so the commit findings stay
    profile(repo, { attributionCheck: { state: 'on', target: 'main' } });
    const r = run(repo, ['--since', 'main']);
    assert.equal(r.status, 1, r.out);
    const branchLines = r.stdout.split(/\r?\n/).filter((l) => /^BRANCH/.test(l));
    assert.equal(branchLines.length, 1, r.stdout);
    assert.match(branchLines[0], /^BRANCH +claude\/task-1 — current branch name · git branch -m claude\/task-1 feature\/task-1$/);
    assert.doesNotMatch(r.stdout, /codex\/x|feature\/y/);
    profile(repo, { attributionCheck: { state: 'on', target: 'main', allow: ['claude/*'] } });
    const ok = run(repo, ['--since', 'main']);
    assert.equal(ok.status, 0, ok.out);
  });
  test('red: AC-1841 usage: an unknown flag, a flag without its value and a ref that is not a commit are exit 2; the sources hold no amend, rebase, branch -m or push call', () => {
    const { repo } = rig();
    profile(repo, { attributionCheck: { state: 'on' } });
    assert.equal(run(repo, ['--bogus']).status, 2);
    assert.equal(run(repo, ['--since']).status, 2);
    assert.equal(run(repo, ['--since', 'no-such-ref']).status, 2);
    const src = readFileSync(join(here, '..', 'scripts', 'lib', 'attribution-check.cjs'), 'utf8') + readFileSync(CLI, 'utf8');
    const calls = [...src.matchAll(/spawnSync\('git',\s*\[([^\]]*)\]/g)].map((m) => m[1]);
    for (const c of calls) assert.doesNotMatch(c, /'(commit|rebase|push|filter-branch|reset)'|'-m'|'-D'/, c);
  });
});
